import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { FilesystemTicketRepository } from '../src/storage/filesystem.js';
import { AuthorizedTicketRepository } from '../src/storage/securityFilter.js';

describe('Headless Worker Runner Loop (Ticket #66)', () => {
  let tempRepo: string;
  let cliScriptPath: string;

  beforeEach(() => {
    tempRepo = fs.mkdtempSync(path.join(os.tmpdir(), 'esedre-crew-worker-test-'));
    cliScriptPath = path.resolve(__dirname, '..', 'dist', 'esedre.mjs');

    // Initialize git repository with initial commit
    execFileSync('git', ['init', '-b', 'main'], { cwd: tempRepo, stdio: 'ignore' });
    execFileSync('git', ['config', 'user.email', 'test@esedre.dev'], { cwd: tempRepo, stdio: 'ignore' });
    execFileSync('git', ['config', 'user.name', 'Esedre Tester'], { cwd: tempRepo, stdio: 'ignore' });

    fs.writeFileSync(path.join(tempRepo, 'README.md'), '# Test Project\n', 'utf-8');
    execFileSync('git', ['add', 'README.md'], { cwd: tempRepo, stdio: 'ignore' });
    execFileSync('git', ['commit', '-m', '[#1] Initial commit'], { cwd: tempRepo, stdio: 'ignore' });

    // Setup .esedre directory and project
    const esedreDir = path.join(tempRepo, '.esedre');
    const ticketsDir = path.join(esedreDir, 'tickets', '1');
    fs.mkdirSync(ticketsDir, { recursive: true });

    fs.writeFileSync(
      path.join(esedreDir, 'esedre.json'),
      JSON.stringify(
        {
          projectCode: 'Core',
          allowedProjects: ['Core'],
        },
        null,
        2
      )
    );

    // Seed ticket #1 assigned to thug-1
    fs.writeFileSync(
      path.join(ticketsDir, 'meta.json'),
      JSON.stringify(
        {
          id: 1,
          title: 'Implement Core Feature in Worktree',
          type: 'Feature',
          category: 'Feature',
          status: 'Planned',
          project: 'Core',
          assignee: 'thug-1',
        },
        null,
        2
      )
    );
    fs.writeFileSync(path.join(ticketsDir, 'detail.md'), '# Ticket #1: Core Feature\n');
  });

  afterEach(() => {
    if (fs.existsSync(tempRepo)) {
      try {
        fs.rmSync(tempRepo, { recursive: true, force: true });
      } catch {}
    }
  });

  const runCli = (
    args: string[],
    envOverrides: Record<string, string> = {},
    cwd: string = tempRepo
  ): { stdout: string; stderr: string; status: number } => {
    try {
      const stdout = execFileSync(process.execPath, [cliScriptPath, ...args], {
        cwd,
        encoding: 'utf-8',
        env: {
          ...process.env,
          ESEDRE_GLOBAL_DIR: path.join(tempRepo, '.global-esedre'),
          ...envOverrides,
        },
      });
      return { stdout, stderr: '', status: 0 };
    } catch (err: any) {
      return {
        stdout: err.stdout ? err.stdout.toString() : '',
        stderr: err.stderr ? err.stderr.toString() : '',
        status: err.status ?? 1,
      };
    }
  };

  it('runs worker in idle state when no tickets match criteria', () => {
    // Run worker for non-matching worker ID
    const res = runCli(['crew', 'worker', '--id', 'thug-99', '--once', '--json']);
    expect(res.status).toBe(0);
    const results = JSON.parse(res.stdout);
    expect(results.length).toBe(1);
    expect(results[0].action).toBe('idle');
  });

  it('executes assigned task in isolated git worktree and completes ticket on success', () => {
    // Execution script creates a file in the worktree
    const execCmd = process.platform === 'win32'
      ? 'node -e "require(\'fs\').writeFileSync(\'output.txt\', \'generated by thug-1\')"'
      : 'node -e "require(\'fs\').writeFileSync(\'output.txt\', \'generated by thug-1\')"';

    const res = runCli([
      'crew',
      'worker',
      '--id',
      'thug-1',
      '--role',
      'thug',
      '--exec',
      execCmd,
      '--once',
      '--json',
    ]);

    expect(res.status).toBe(0);
    const results = JSON.parse(res.stdout);
    expect(results.length).toBe(1);
    expect(results[0].ticketId).toBe(1);
    expect(results[0].action).toBe('claimed_and_completed');

    // Verify ticket state updated to Completed and lease is released
    const rawRepo = new FilesystemTicketRepository(tempRepo, { projectCode: 'Core' });
    const authRepo = new AuthorizedTicketRepository(rawRepo, { projectCode: 'Core' });

    // Verify via CLI get
    const getRes = runCli(['get', '1', '--json']);
    const ticket = JSON.parse(getRes.stdout);
    expect(ticket.meta.status).toBe('Completed');
    expect(ticket.meta.lease).toBeNull();

    // Verify git isolation: output.txt was committed on branch in worktree
    const worktreePath = path.join(tempRepo, '.worktrees', 'thug-1');
    expect(fs.existsSync(path.join(worktreePath, 'output.txt'))).toBe(true);

    // output.txt is NOT in the main repo root
    expect(fs.existsSync(path.join(tempRepo, 'output.txt'))).toBe(false);

    // Verify git log on the thug branch contains the automated commit
    const log = execFileSync('git', ['log', 'thug/thug-1', '-n', '1', '--oneline'], {
      cwd: tempRepo,
      encoding: 'utf-8',
    });
    expect(log).toContain('[#1] Execute automated worker task (thug-1)');
  });

  it('automatically escalates task to Planned when execution command fails', () => {
    // Execution command exits with error code 1
    const failingCmd = 'node -e "process.exit(1)"';

    const res = runCli([
      'crew',
      'worker',
      '--id',
      'thug-1',
      '--role',
      'thug',
      '--exec',
      failingCmd,
      '--once',
      '--json',
    ]);

    expect(res.status).toBe(0);
    const results = JSON.parse(res.stdout);
    expect(results.length).toBe(1);
    expect(results[0].action).toBe('claimed_and_escalated');

    // Verify ticket status reset to Planned and lease released
    const getRes = runCli(['get', '1', '--json']);
    const ticket = JSON.parse(getRes.stdout);
    expect(ticket.meta.status).toBe('Planned');
    expect(ticket.meta.lease).toBeNull();

    // Verify escalation comment was added to notify Lead/Anchor
    const comments = ticket.comments;
    const lastComment = comments[comments.length - 1];
    expect(lastComment.text).toContain('[Escalation] Automated worker execution failed');
  });

  it('supports dry-run mode without modifying ticket lease or running task', () => {
    const res = runCli([
      'crew',
      'worker',
      '--id',
      'thug-1',
      '--dry-run',
      '--once',
      '--json',
    ]);

    expect(res.status).toBe(0);
    const results = JSON.parse(res.stdout);
    expect(results[0].action).toBe('claimed_and_held');

    // Ticket remains in Planned status with no lease
    const getRes = runCli(['get', '1', '--json']);
    const ticket = JSON.parse(getRes.stdout);
    expect(ticket.meta.status).toBe('Planned');
    expect(ticket.meta.lease).toBeUndefined();
  });

  it('throttles new ticket claims when worker pool limit (maxWorkers) is reached', () => {
    // 1. Worker thug-1 claims ticket #1
    const claimRes = runCli(['claim', '1', '--worker', 'thug-1', '--ttl', '30', '--json']);
    expect(claimRes.status).toBe(0);

    // 2. Seed a second unassigned planned ticket #2
    const ticketsDir2 = path.join(tempRepo, '.esedre', 'tickets', '2');
    fs.mkdirSync(ticketsDir2, { recursive: true });
    fs.writeFileSync(
      path.join(ticketsDir2, 'meta.json'),
      JSON.stringify(
        {
          id: 2,
          title: 'Second Feature Ready for Work',
          type: 'Feature',
          category: 'Feature',
          status: 'Planned',
          project: 'Core',
        },
        null,
        2
      )
    );
    fs.writeFileSync(path.join(ticketsDir2, 'detail.md'), '# Ticket #2\n');

    // 3. Worker thug-2 attempts to run with max-workers=1
    const workerRes = runCli([
      'crew',
      'worker',
      '--id',
      'thug-2',
      '--once',
      '--max-workers',
      '1',
      '--json',
    ]);

    expect(workerRes.status).toBe(0);
    const results = JSON.parse(workerRes.stdout);
    // Since maxWorkers limit (1) is active on this system, thug-2 idles
    expect(results[0].action).toBe('idle');

    // Ticket #2 remains unleased
    const get2 = runCli(['get', '2', '--json']);
    const ticket2 = JSON.parse(get2.stdout);
    expect(ticket2.meta.lease).toBeUndefined();
  });
});

